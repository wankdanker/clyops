#!/usr/bin/env node
// Single-file CommonJS builds of the Node packages, committed to the repo so
// projects can link or copy one file (as they do clyops.sh) and `require()`
// it on any supported Node, with no build step and no node_modules.
//
//   node tools/bundle-js.mjs          # rewrite the bundles
//   node tools/bundle-js.mjs --check  # exit 1 if any is stale (CI)
//
// esbuild is pinned exactly in the root package.json so the output is
// reproducible.
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const bundles = [
  { entry: 'packages/js/src/index.ts', out: 'packages/js/clyops.cjs' },
  { entry: 'packages/tools/src/index.ts', out: 'packages/tools/clyops-tools.cjs' },
  // Includes clyops-tools, so it is the one file a project needs for the job engine.
  { entry: 'packages/jobs/src/index.ts', out: 'packages/jobs/clyops-jobs.cjs' },
];

const check = process.argv.includes('--check');
const stale = [];
for (const b of bundles) {
  const result = await build({
    entryPoints: [join(root, b.entry)],
    bundle: true,
    platform: 'node',
    format: 'cjs',
    target: 'node20',
    write: false,
    legalComments: 'none',
    // Workspace packages come from source, not from their (unbuilt) dist.
    alias: { 'clyops-tools': join(root, 'packages/tools/src/index.ts') },
    banner: { js: `// Generated by tools/bundle-js.mjs from ${b.entry}. Do not edit.` },
    logLevel: 'warning',
    // Paths in esbuild's comments are relative to this: keep them repo-relative wherever it runs.
    absWorkingDir: root,
  });
  const text = result.outputFiles[0].text;
  const path = join(root, b.out);
  let current = null;
  try {
    current = readFileSync(path, 'utf8');
  } catch {}
  if (current === text) continue;
  stale.push(b.out);
  if (!check) writeFileSync(path, text);
}
if (check && stale.length) {
  console.error(`stale bundles (run node tools/bundle-js.mjs):\n  ${stale.join('\n  ')}`);
  process.exit(1);
}
console.log(stale.length ? (check ? 'up to date' : `updated: ${stale.join(', ')}`) : 'up to date');
