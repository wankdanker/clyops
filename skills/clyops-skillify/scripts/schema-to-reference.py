#!/usr/bin/env python3
# clyops-tool
"""Render a clyops tool's --help-json-schema as a Markdown reference page.

We keep the rendering in `render()` so it can be unit tested and reused; the
clyops CLI below is only a thin wrapper around it.
"""
import json
import sys

from clyops import Cli, die

MARKER = "<!-- Generated by clyops-skillify from --help-json-schema. Do not edit; regenerate instead. -->"


def _cell(text):
    """Make a value safe for a Markdown table cell."""
    return str(text).replace("|", "\\|").replace("\n", " ")


def _option_rows(options):
    rows = ["| Option | Type / rule | Default | Notes |", "| --- | --- | --- | --- |"]
    for opt in options:
        if opt["name"] == "help":
            continue
        label = f"`--{opt['name']}`" + (f", `-{opt['shortName']}`" if opt["shortName"] else "")
        rule = opt["validation"] or opt["type"]
        if opt["isFlag"]:
            default = "off"
        elif opt["required"]:
            default = "**required**"
        else:
            default = f"`{opt['default']}`" if opt["default"] else ""
        notes = [opt["description"]]
        if opt["isArray"]:
            notes.append("repeatable")
        if opt.get("secret"):
            notes.append(f"**secret**: pass via env `{opt['variableName']}`, never on the command line")
        else:
            notes.append(f"env `{opt['variableName']}`")
        rows.append(f"| {label} | {_cell(rule)} | {_cell(default)} | {_cell('; '.join(notes))} |")
    return rows


def _argument_rows(arguments):
    rows = ["| Argument | Rule | Default | Description |", "| --- | --- | --- | --- |"]
    for arg in arguments:
        name = f"`{arg['name']}`" + (" (variadic)" if arg["isVariadic"] else "")
        default = "**required**" if arg["required"] else (f"`{arg['default']}`" if arg["default"] else "")
        rows.append(f"| {name} | {_cell(arg['validation'] or 'text')} | {default} | {_cell(arg['description'])} |")
    return rows


def _usage(words, arguments):
    parts = list(words)
    for arg in arguments:
        if arg["isVariadic"]:
            parts.append(f"[<{arg['name']}>...]")
        elif arg["required"]:
            parts.append(f"<{arg['name']}>")
        else:
            parts.append(f"[<{arg['name']}>]")
    return " ".join(parts + ["[OPTIONS]"])


def _section(level, words, node, options, effects, stdin, stdout, constraints, required):
    """Render one runnable tool (a program without commands, or a leaf command)."""
    out = [f"{'#' * level} `{' '.join(words)}`", ""]
    if node.get("description"):
        out += [node["description"], ""]
    out += ["```sh", _usage(words, node["arguments"]), "```", ""]
    facts = [f"- **Effects:** {', '.join(effects) if effects else 'not declared (treat as possibly destructive)'}"]
    if stdin:
        facts.append(f"- **stdin:** {stdin['description']} (`{stdin['contentType']}`)")
    if stdout:
        facts.append(f"- **stdout:** {stdout['description']} (`{stdout['contentType']}`)")
    for c in constraints:
        names = ", ".join(f"`--{o}`" for o in c["options"])
        facts.append({"exclusive": f"- **At most one of:** {names}",
                      "requires": f"- **`--{c['options'][0]}` requires:** "
                                  + ", ".join(f"`--{o}`" for o in c["options"][1:]),
                      "oneOf": f"- **At least one of:** {names}"}[c["type"]])
    for r in required:
        hint = f" (install: {r['installHint']})" if r.get("installHint") else ""
        facts.append(f"- **Needs on PATH:** `{r['command']}`: {r['description']}{hint}")
    out += facts + [""]
    if node["arguments"]:
        out += _argument_rows(node["arguments"]) + [""]
    if any(o["name"] != "help" for o in options):
        out += _option_rows(options) + [""]
    return out


def render(schema, invocation):
    """Return the Markdown reference for a parsed --help-json-schema document.

    `invocation` is how the tool is run (e.g. `mytool media to-pcm` through a
    dispatcher). A program with commands gets one section per leaf command,
    with inherited options, the nearest declared effects/stdin/stdout, and
    every constraint and required command on the way (spec section 13).
    """
    if schema.get("clyops") != 1:
        raise ValueError("not a clyops schema (missing \"clyops\": 1)")
    lines = [MARKER, "", f"# {invocation}", ""]
    if schema.get("epilog"):
        lines += [schema["epilog"].rstrip(), ""]

    def walk(node, words, inherited, effects, stdin, stdout, constraints, required):
        options = list(node["options"]) + inherited
        effects = node.get("effects") or effects
        stdin = node.get("stdin") or stdin
        stdout = node.get("stdout") or stdout
        constraints = constraints + node.get("constraints", [])
        required = required + node.get("requiredCommands", [])
        if not node.get("commands"):
            return _section(2, words, node, options, effects, stdin, stdout, constraints, required)
        out = []
        for child in node["commands"]:
            out += walk(child, words + [child["name"]], options, effects, stdin, stdout, constraints, required)
        return out

    lines += walk(schema, invocation.split(), [], [], None, None, [], [])
    return "\n".join(lines).rstrip() + "\n"


if __name__ == "__main__":
    cli = Cli(name="schema-to-reference.py")
    cli.set_description("Render a clyops tool's --help-json-schema as a Markdown reference page for an agent skill.")
    cli.opt("INVOCATION", "invocation", "i", "", "How the tool is run, e.g. 'mytool media to-pcm'", "Output")
    cli.opt("SCHEMA", "schema", "s", "optional", "Read the schema from this file instead of stdin", "Input",
            "file:readable")
    cli.set_effects("read-only")
    cli.set_stdin("The tool's --help-json-schema output (when --schema is omitted)", "application/json")
    cli.set_stdout("Markdown reference page", "text/markdown")
    args = cli.run()
    try:
        if args.SCHEMA:
            with open(args.SCHEMA, encoding="utf-8") as file:
                doc = json.load(file)
        else:
            doc = json.load(sys.stdin)
        sys.stdout.write(render(doc, args.INVOCATION))
    except (OSError, ValueError) as error:
        die(1, f"Cannot render reference: {error}")
